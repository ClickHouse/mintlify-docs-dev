/**
 * Compare the current reference route tree with a snapshot-rendered tree.
 *
 * This deliberately uses the file-derived URLs that Nimbus serves today, not
 * stale frontmatter `slug` values. It is intended to run after
 * generate-reference-prototype.ts and makes route changes explicit before a
 * archived reference routing is enabled.
 */
import fs from "node:fs";
import path from "node:path";

type Page = {
  file: string;
  route: string;
  title?: string;
  autogenerated: boolean;
  siteContentOutsideGenerated: boolean;
  siteContentCharacters: number;
  siteContentExcerpt?: string;
};
type RouteContractEntry = {
  route: string;
  disposition: string;
  note: string;
};

const root = process.cwd();
const currentRoot = path.join(root, "reference");
const prototypeRoot = path.join(root, "reference-prototype");
const reportRoot = path.join(root, "reports");

function files(directory: string): string[] {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return files(target);
    return /\.mdx?$/.test(entry.name) ? [target] : [];
  });
}

function readTitle(source: string): string | undefined {
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const title = frontmatter?.[1].match(/^title:\s*['"]?(.+?)['"]?\s*$/m)?.[1];
  return title?.replace(/^['"]|['"]$/g, "");
}

function siteContentOutsideGenerated(source: string) {
  const start = "{/*AUTOGENERATED_START*/}";
  const end = "{/*AUTOGENERATED_END*/}";
  const startIndex = source.indexOf(start);
  if (startIndex === -1) return "";

  const endIndex = source.indexOf(end, startIndex + start.length);
  const outside = endIndex === -1
    ? source.slice(0, startIndex)
    : `${source.slice(0, startIndex)}\n${source.slice(endIndex + end.length)}`;

  // Frontmatter, imports, and MDX comments provide page metadata or plumbing;
  // they are not page content outside the generated region.
  return outside
    .replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, "")
    .replace(/^import\s.+?;?\s*$/gm, "")
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function routeFor(file: string, sourceRoot: string, prototype = false): string {
  let relative = path.relative(sourceRoot, file).replace(/\.mdx?$/, "").split(path.sep).join("/");
  if (relative === "index") relative = "";
  else relative = relative.replace(/\/index$/, "");
  return `/${prototype ? "reference" : "reference"}${relative ? `/${relative}` : ""}`;
}

function pages(sourceRoot: string, prototype = false): Page[] {
  return files(sourceRoot).filter((file) => {
    const relative = path.relative(sourceRoot, file).split(path.sep);
    const basename = path.basename(file, path.extname(file)).toLowerCase();
    // Snippets and agent/readme files are repository inputs, not public docs
    // routes. They would otherwise inflate the site-owned-page inventory.
    return !relative.some((segment) => segment.startsWith("_")) && !["agents", "readme"].includes(basename);
  }).map((file) => {
    const source = fs.readFileSync(file, "utf8");
    const siteContent = siteContentOutsideGenerated(source);
    return {
      file: path.relative(root, file),
      route: routeFor(file, sourceRoot, prototype),
      title: readTitle(source),
      autogenerated: /\{\/\*AUTOGENERATED_START\*\/\}/.test(source),
      siteContentOutsideGenerated: siteContent.length > 0,
      siteContentCharacters: siteContent.length,
      siteContentExcerpt: siteContent.replace(/\s+/g, " ").slice(0, 220) || undefined,
    };
  }).sort((left, right) => left.route.localeCompare(right.route));
}

function normalizedRoute(route: string) {
  return route.toLowerCase().replace(/[^a-z0-9]/g, "");
}

function category(route: string) {
  return route.split("/").filter(Boolean).slice(1, 3).join("/") || "reference root";
}

function byCategory(pages: Page[]) {
  return [...pages.reduce((counts, page) => {
    const key = category(page.route);
    counts.set(key, (counts.get(key) ?? 0) + 1);
    return counts;
  }, new Map<string, number>()).entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, count]) => ({ name, count }));
}

function byTopLevel(pages: Page[]) {
  return [...pages.reduce((counts, page) => {
    const key = page.route.split("/").filter(Boolean)[1] ?? "reference root";
    counts.set(key, (counts.get(key) ?? 0) + 1);
    return counts;
  }, new Map<string, number>()).entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, count]) => ({ name, count }));
}

const current = pages(currentRoot);
const generated = pages(prototypeRoot, true);
const currentByRoute = new Map(current.map((page) => [page.route, page]));
const generatedByRoute = new Map(generated.map((page) => [page.route, page]));
const routeContractPath = path.join(prototypeRoot, "route-contract.json");
const routeContractEntries: RouteContractEntry[] = fs.existsSync(routeContractPath)
  ? (JSON.parse(fs.readFileSync(routeContractPath, "utf8")) as { entries?: RouteContractEntry[] }).entries ?? []
  : [];
const routeContractByRoute = new Map(routeContractEntries.map((entry) => [entry.route, entry]));
const currentAutogenerated = current.filter((page) => page.autogenerated);
const currentManual = current.filter((page) => !page.autogenerated);
// This is about the website file shape only, not documentation provenance.
// The generated region is source-owned: `system.documentation.description`
// exports the full Markdown body, including explanatory prose, from the
// ClickHouse source registration. For example, Statement rows use the full
// `Documentation::description` verbatim.
const currentWithSiteContentOutsideGenerated = currentAutogenerated.filter((page) => page.siteContentOutsideGenerated);
const currentMarkerWrapped = currentAutogenerated.filter((page) => !page.siteContentOutsideGenerated);
const exact = generated.filter((page) => currentByRoute.has(page.route));
const generatedNew = generated.filter((page) => !currentByRoute.has(page.route));
const currentAutogeneratedOmitted = currentAutogenerated.filter((page) => !generatedByRoute.has(page.route));

const currentByNormalizedRoute = new Map<string, Page[]>();
for (const page of current) {
  const key = normalizedRoute(page.route);
  currentByNormalizedRoute.set(key, [...(currentByNormalizedRoute.get(key) ?? []), page]);
}
const currentByTitle = new Map<string, Page[]>();
for (const page of current) {
  if (!page.title) continue;
  const key = page.title.toLowerCase();
  currentByTitle.set(key, [...(currentByTitle.get(key) ?? []), page]);
}
const generatedByTitle = new Map<string, Page[]>();
for (const page of generated) {
  if (!page.title) continue;
  const key = page.title.toLowerCase();
  generatedByTitle.set(key, [...(generatedByTitle.get(key) ?? []), page]);
}

function uniqueCandidate(page: Page, candidates: Page[]) {
  return candidates.length === 1 && candidates[0].route !== page.route ? candidates[0] : undefined;
}

const normalizedRoutePairs = generatedNew.flatMap((page) => {
  const match = uniqueCandidate(page, currentByNormalizedRoute.get(normalizedRoute(page.route)) ?? []);
  return match ? [{ generated: page, current: match }] : [];
});
const titlePairs = generatedNew.flatMap((page) => {
  if (!page.title) return [];
  // Same title is only useful when it identifies one record in both trees and
  // remains within the same broad catalog. Without those constraints, names
  // such as File, Dictionary, and JSON create misleading redirect proposals.
  if ((generatedByTitle.get(page.title.toLowerCase()) ?? []).length !== 1) return [];
  const match = uniqueCandidate(page, currentByTitle.get(page.title.toLowerCase()) ?? []);
  return match && category(match.route).split("/")[0] === category(page.route).split("/")[0]
    ? [{ generated: page, current: match }]
    : [];
}).filter((pair) => !normalizedRoutePairs.some((normalized) => normalized.generated.route === pair.generated.route));
const candidateGeneratedRoutes = new Set([...normalizedRoutePairs, ...titlePairs].map((pair) => pair.generated.route));
const candidateCurrentRoutes = new Set([...normalizedRoutePairs, ...titlePairs].map((pair) => pair.current.route));
const currentAutogeneratedCovered = currentAutogenerated.filter((page) =>
  generatedByRoute.has(page.route) || candidateCurrentRoutes.has(page.route),
);
const currentAutogeneratedStillUncovered = currentAutogenerated.filter((page) => !currentAutogeneratedCovered.includes(page));
const classifiedLegacyExceptions = currentAutogeneratedStillUncovered.flatMap((page) => {
  const decision = routeContractByRoute.get(page.route);
  return decision ? [{ page, decision }] : [];
});
const unclassifiedLegacyExceptions = currentAutogeneratedStillUncovered.filter((page) => !routeContractByRoute.has(page.route));
const intentionalSnapshotOmissions = classifiedLegacyExceptions.filter(({ decision }) => decision.disposition === "snapshot-omitted");
const statementPages = current.filter((page) => page.route === "/reference/statements" || page.route.startsWith("/reference/statements/"));
const statementManualPages = statementPages.filter((page) => !page.autogenerated);
const statementMarkerWrappedPages = statementPages.filter((page) => page.autogenerated);

const report = {
  generatedAt: new Date().toISOString(),
  summary: {
    currentPages: current.length,
    currentAutogeneratedPages: currentAutogenerated.length,
    currentManualPages: currentManual.length,
    currentPagesWithSiteContentOutsideGenerated: currentWithSiteContentOutsideGenerated.length,
    currentMarkerWrappedPages: currentMarkerWrapped.length,
    currentAutogeneratedRoutesWithoutSnapshotCounterpart: currentAutogeneratedStillUncovered.length,
    classifiedLegacyExceptions: classifiedLegacyExceptions.length,
    unclassifiedLegacyExceptions: unclassifiedLegacyExceptions.length,
    intentionalSnapshotOmissions: intentionalSnapshotOmissions.length,
    generatedPages: generated.length,
    exactRouteMatches: exact.length,
    generatedRoutesWithoutCurrentPage: generatedNew.length,
    currentAutogeneratedRoutesNotGenerated: currentAutogeneratedOmitted.length,
    normalizedRouteCandidates: normalizedRoutePairs.length,
    titleCandidates: titlePairs.length,
    generatedRoutesCoveredByExactOrCandidate: exact.length + candidateGeneratedRoutes.size,
    currentAutogeneratedRoutesCoveredByExactOrCandidate: currentAutogeneratedCovered.length,
    currentAutogeneratedRoutesStillUncovered: unclassifiedLegacyExceptions.length,
  },
  currentManualByCategory: byCategory(currentManual),
  currentPagesWithSiteContentOutsideGeneratedByTopLevel: byTopLevel(currentWithSiteContentOutsideGenerated),
  currentAutogeneratedRoutesWithoutSnapshotCounterpartByTopLevel: byTopLevel(currentAutogeneratedStillUncovered),
  exactByTopLevel: byTopLevel(exact),
  generatedNewByCategory: byTopLevel(generatedNew),
  currentAutogeneratedOmittedByCategory: byTopLevel(currentAutogeneratedOmitted),
  currentAutogeneratedStillUncoveredByCategory: byTopLevel(unclassifiedLegacyExceptions),
  normalizedRouteCandidates: normalizedRoutePairs.map(({ generated, current }) => ({ from: current.route, to: generated.route, title: generated.title })),
  titleCandidates: titlePairs.map(({ generated, current }) => ({ from: current.route, to: generated.route, title: generated.title })),
  currentManualPages: currentManual.map(({ route, title, file }) => ({ route, title, file })),
  currentPagesWithSiteContentOutsideGenerated: currentWithSiteContentOutsideGenerated.map(({ route, title, file, siteContentCharacters, siteContentExcerpt }) => ({
    route,
    title,
    file,
    siteContentCharacters,
    siteContentExcerpt,
  })),
  currentAutogeneratedRoutesWithoutSnapshotCounterpart: currentAutogeneratedStillUncovered.map(({ route, title, file }) => ({ route, title, file })),
  classifiedLegacyExceptions: classifiedLegacyExceptions.map(({ page, decision }) => ({ route: page.route, title: page.title, file: page.file, disposition: decision.disposition, note: decision.note })),
  unclassifiedLegacyExceptions: unclassifiedLegacyExceptions.map(({ route, title, file }) => ({ route, title, file })),
  statements: {
    pages: statementPages.length,
    sourceOwnedPages: statementManualPages.length,
    markerWrappedPages: statementMarkerWrappedPages.length,
    sourceOwnedRoutes: statementManualPages.map((page) => page.route),
    markerWrappedRoutes: statementMarkerWrappedPages.map((page) => page.route),
  },
  generatedRoutesWithoutCurrentPage: generatedNew.map(({ route, title, file }) => ({ route, title, file })),
  currentAutogeneratedRoutesNotGenerated: currentAutogeneratedOmitted.map(({ route, title, file }) => ({ route, title, file })),
};

function bulletList(items: Array<{ name: string; count: number }>) {
  return items.map((item) => `- \`${item.name}\`: ${item.count}`).join("\n") || "- None";
}
function routeList(items: Array<{ from: string; to: string; title?: string }>, limit = 30) {
  return items.slice(0, limit).map((item) => `- \`${item.from}\` → \`${item.to}\`${item.title ? ` — ${item.title}` : ""}`).join("\n") || "- None";
}
function classifiedExceptionList(items: typeof classifiedLegacyExceptions) {
  return items.map(({ page, decision }) => `- \`${page.route}\` — **${decision.disposition}**: ${decision.note}`).join("\n") || "- None";
}

