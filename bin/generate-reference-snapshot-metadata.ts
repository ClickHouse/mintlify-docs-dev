/**
 * Produce the versioned routing/navigation metadata that accompanies a
 * ClickHouse reference snapshot. This is a transitional local producer: the
 * same output belongs in ClickHouse snapshot CI once the format is accepted.
 *
 * The renderer consumes only `metadata/reference-site.json`; it never reads
 * the authored reference tree for version-specific routing.
 */
import fs from "node:fs";
import path from "node:path";
import { ROUTE_CONTRACT_ENTRIES, type RouteContractEntry } from "./reference-route-contract.ts";

type Catalog = { name: string; path: string; rows: number; sha256: string };
type NavigationItem = { label: string; link?: string; items?: NavigationItem[]; collapsed?: boolean };
type LegacyRoute = { route: string; title?: string; keys: string[]; embeddedKeys: string[] };
type SettingsGroup = { label: string; prefix?: string; route: string };
type SourceOwnedFunctionPage = { title: string; route: string; description: string; body: string };

const snapshotRoot = process.env.REFERENCE_SNAPSHOT_DIR;
if (!snapshotRoot) throw new Error("REFERENCE_SNAPSHOT_DIR must point to a reference snapshot");
const resolvedSnapshotRoot = path.resolve(snapshotRoot);
const manifest = JSON.parse(fs.readFileSync(path.join(resolvedSnapshotRoot, "manifest.json"), "utf8")) as {
  schemaVersion: number;
  clickhouseVersion: string;
  catalogs: Catalog[];
};
if (manifest.schemaVersion !== 1) throw new Error(`Unsupported reference snapshot schema: ${manifest.schemaVersion}`);

const routeKey = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "");
const referenceRoot = path.join(process.cwd(), "reference");
const sidebar = JSON.parse(fs.readFileSync(path.join(process.cwd(), "src", "generated", "sidebar.items.json"), "utf8")) as NavigationItem[];

function frontmatterTitle(source: string) {
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  return frontmatter?.[1].match(/^title:\s*['"]?(.+?)['"]?\s*$/m)?.[1]?.replace(/^['"]|['"]$/g, "");
}

function legacyRouteIndex(relativeDirectory: string): LegacyRoute[] {
  const root = path.join(referenceRoot, relativeDirectory);
  if (!fs.existsSync(root)) throw new Error(`Reference taxonomy source is missing ${relativeDirectory}`);
  const routes: LegacyRoute[] = [];
  const walk = (directory: string) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const target = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (!entry.name.startsWith("_")) walk(target);
        continue;
      }
      if (!/\.mdx?$/.test(entry.name)) continue;
      const raw = fs.readFileSync(target, "utf8");
      const title = frontmatterTitle(raw);
      const relative = path.relative(referenceRoot, target).replace(/\.mdx?$/, "").replace(/\/index$/, "");
      const normalizedTitle = title?.replace(/\b(?:table|database) engine\b|\btable function\b|\bdictionary (?:layout|source)\b|\bformat\b|\bdata type\b/gi, "").trim();
      const withoutSystemPrefix = title?.replace(/^system\./i, "");
      const generatedBody = raw.match(/\{\/\*AUTOGENERATED_START\*\/\}([\s\S]*?)\{\/\*AUTOGENERATED_END\*\/\}/)?.[1] ?? "";
      routes.push({
        route: relative,
        title,
        keys: [path.basename(relative), title, normalizedTitle, withoutSystemPrefix]
          .filter((value): value is string => Boolean(value))
          .map(routeKey),
        embeddedKeys: [...generatedBody.matchAll(/^#{2,6}\s+(.+)$/gm)]
          .map((match) => match[1].replace(/\s+\{#[^}]+\}\s*$/, "").replace(/`/g, "").trim())
          .filter(Boolean)
          .map(routeKey),
      });
    }
  };
  walk(root);
  return routes;
}

function findNavigationItem(items: NavigationItem[], predicate: (item: NavigationItem) => boolean): NavigationItem | undefined {
  for (const item of items) {
    if (predicate(item)) return item;
    const nested = item.items && findNavigationItem(item.items, predicate);
    if (nested) return nested;
  }
}

function sessionSettingsGroups(): SettingsGroup[] {
  const session = findNavigationItem(sidebar, (item) =>
    Boolean(item.label === "Session Settings" && item.items?.some((child) => child.link?.startsWith("/reference/settings/session-settings/"))),
  );
  if (!session?.items?.length) throw new Error("Could not find Session Settings in sidebar.items.json");
  return session.items.map((item) => {
    if (!item.link) throw new Error(`Session Settings item is missing a route: ${item.label}`);
    return item.label === "Other"
      ? { label: item.label, route: item.link.replace(/^\/reference\//, "") }
      : { label: item.label, prefix: item.label.replace(/_\*$/, ""), route: item.link.replace(/^\/reference\//, "") };
  });
}

function prefixSettingsGroups(sidebarLabel: string, overviewRoute: string): SettingsGroup[] {
  const routePrefix = `/reference/${overviewRoute}`;
  const catalog = findNavigationItem(sidebar, (item) =>
    Boolean(item.label === sidebarLabel && item.items?.some((child) => child.link?.startsWith(routePrefix))),
  );
  if (!catalog?.items?.length) throw new Error(`Could not find ${sidebarLabel} in sidebar.items.json`);
  return catalog.items
    .filter((item) => item.link && item.link !== routePrefix)
    .map((item) => ({
      label: item.label,
      prefix: item.label === "Other" ? undefined : item.label.replace(/_\*$/, ""),
      route: item.link!.replace(/^\/reference\//, ""),
    }));
}

function sourceOwnedFunctionPage(sourcePath: string): SourceOwnedFunctionPage {
  const raw = fs.readFileSync(path.join(process.cwd(), sourcePath), "utf8");
  const frontmatterMatch = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!frontmatterMatch) throw new Error(`Expected frontmatter in ${sourcePath}`);
  const field = (name: string) => frontmatterMatch[1].match(new RegExp(`^${name}:\\s*['\"]?([^'\"\\n]+)`, "m"))?.[1]?.trim();
  const route = sourcePath.replace(/^reference\//, "").replace(/\.mdx?$/, "").replace(/\/index$/, "");
  const title = field("title") ?? path.basename(route);
  return {
    title,
    route,
    description: field("description") ?? `${title} reference documentation.`,
    body: raw.slice(frontmatterMatch[0].length).replace(/(\/reference\/functions\/(?:aggregate-functions|window-functions))\/index(?=[#)\s])/g, "$1"),
  };
}

const legacyDirectories = [
  "functions/regular-functions",
  "functions/aggregate-functions",
  "functions/window-functions",
  "statements",
  "statements/create/dictionary/layouts",
  "statements/create/dictionary/sources",
  "data-types",
  "engines/table-engines",
  "engines/database-engines",
  "functions/table-functions",
  "formats",
  "settings",
  "system-tables",
] as const;

const sourceOwnedFunctionPaths = [
  "reference/functions/aggregate-functions/index.mdx",
  "reference/functions/aggregate-functions/combinators.mdx",
  "reference/functions/aggregate-functions/first_value.mdx",
  "reference/functions/aggregate-functions/groupArrayArray.mdx",
  "reference/functions/aggregate-functions/grouping_function.mdx",
  "reference/functions/aggregate-functions/last_value.mdx",
  "reference/functions/aggregate-functions/median.mdx",
  "reference/functions/aggregate-functions/parametric-functions.mdx",
  "reference/functions/window-functions/index.mdx",
  "reference/functions/window-functions/first_value.mdx",
  "reference/functions/window-functions/last_value.mdx",
];

const output = {
  schemaVersion: 1,
  clickhouseVersion: manifest.clickhouseVersion,
  catalogs: manifest.catalogs.map(({ name, rows, sha256 }) => ({ name, rows, sha256 })),
  routeContract: { entries: ROUTE_CONTRACT_ENTRIES satisfies RouteContractEntry[] },
  legacyRoutes: Object.fromEntries(legacyDirectories.map((directory) => [directory, legacyRouteIndex(directory)])),
  sourceOwnedFunctionPages: sourceOwnedFunctionPaths.map(sourceOwnedFunctionPage),
  settingsGroups: {
    session: sessionSettingsGroups(),
    server: prefixSettingsGroups("Server Settings", "settings/server-settings/settings"),
    mergeTree: prefixSettingsGroups("MergeTree tables settings", "settings/merge-tree-settings"),
  },
  functionRouteOverrides: {
    maxMappedArrays: "functions/aggregate-functions/maxMap",
    minMappedArrays: "functions/aggregate-functions/minMap",
    sumMappedArrays: "functions/aggregate-functions/sumMap",
  },
  windowFunctionNames: [
    "cume_dist", "denseRank", "lag", "lagInFrame", "lead", "leadInFrame",
    "first_value", "last_value", "nonNegativeDerivative", "nth_value", "ntile", "percentRank", "rank", "row_number",
  ],
};

const outputDirectory = path.join(resolvedSnapshotRoot, "metadata");
fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(path.join(outputDirectory, "reference-site.json"), JSON.stringify(output, null, 2) + "\n");
console.log(`generate-reference-snapshot-metadata: wrote metadata/reference-site.json for ClickHouse ${manifest.clickhouseVersion}`);
